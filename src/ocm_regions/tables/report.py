"""Write the issues report and coverage summary."""

import json
from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Final, TypedDict

from ocm_regions.common.schema import CallRow, Grade, ProviderId
from ocm_regions.fetch.sources import StrPath
from ocm_regions.tables.coverage import CodedRow, Coverage, SchemeName, scheme_coverage
from ocm_regions.tables.grades import GRADES

SCHEME_LABELS: Final[dict[SchemeName, str]] = {
    "iata_nearest_airport": "IATA airport, nearest (nearest airport)",
    "iata_major_hub": "IATA airport, best connected within 200 km (major hub)",
    "iata_nearby_hub": "IATA airport, major hub within the cap, otherwise nearest (nearby hub)",
    "iata_metro": "IATA metro (OpenTravelData) only",
    "metro_or_airport": "IATA metro, airport as fallback",
    "unlocode": "UN/LOCODE",
    "clli": "CLLI prefix (inferred)",
}


class ProviderGrade(TypedDict):
    """A region's vendor and grade."""

    provider: ProviderId
    grade: Grade


class ReportRow(CodedRow, ProviderGrade):
    """A region row as the report reads it."""


class StatusRow(TypedDict):
    """A row that carries a check status."""

    status: str


def grades_by_provider(rows: Iterable[ProviderGrade]) -> dict[ProviderId, Counter[Grade]]:
    """Count regions per grade for each vendor.

    Args:
        rows: Vendor and grade of each region.

    Returns:
        Counts per grade keyed by vendor.
    """
    counts: dict[ProviderId, Counter[Grade]] = {}
    for row in rows:
        counts.setdefault(row["provider"], Counter())[row["grade"]] += 1
    return counts


def verification_section(results: Iterable[Mapping[str, object]]) -> list[str]:
    """The Markdown section that counts quote check results by status.

    Args:
        results: Quote check results.

    Returns:
        The section's lines.
    """
    counts = Counter(r["status"] for r in results)
    lines = [
        "## Evidence link check",
        "",
        "From `ocm-regions verify`. A miss can mean a blocked script, a page rendered by JavaScript or a changed page, so it needs a human look.",
        "",
        "| Status | Records |",
        "|---|---:|",
    ]
    lines += [f"| {status} | {n} |" for status, n in sorted(counts.items())]
    return [*lines, ""]


def write_report(
    rows: Sequence[ReportRow],
    calls: Sequence[CallRow],
    output_dir: StrPath,
    extra_sections: Sequence[str] = (),
) -> Coverage:
    """Write the coverage report and return the scheme coverage.

    Args:
        rows: Region rows.
        calls: Review calls.
        output_dir: Output folder.
        extra_sections: Markdown lines to append to the report.

    Returns:
        Coverage keyed by scheme.
    """
    output = Path(output_dir)
    coverage = scheme_coverage(rows)
    _ = (output / "coverage.json").write_text(json.dumps(coverage, indent=2) + "\n", encoding="utf-8")
    sections = [
        "# Location taxonomy report",
        "",
        "Generated by `ocm-regions build`. Do not edit by hand.",
        "",
        "## Code scheme coverage",
        "",
        *_coverage_lines(coverage, len(rows)),
        "",
        "## Evidence grade by provider",
        "",
        *_grade_lines(rows),
        "",
        "## Calls and gaps",
        "",
        *_call_lines(calls),
        "",
        "## High-severity issues",
        "",
        *_high_lines(calls),
        "",
        *extra_sections,
    ]
    _ = (output / "report.md").write_text("\n".join(sections).rstrip() + "\n", encoding="utf-8")
    return coverage


def _call_lines(calls: Iterable[CallRow]) -> list[str]:
    """The Markdown table of calls by severity and kind.

    Args:
        calls: Review calls.

    Returns:
        The table's lines.
    """
    lines = ["| Severity | Kind | Count |", "|---|---|---:|"]
    for (severity, kind), n in sorted(Counter((c["severity"], c["kind"]) for c in calls).items()):
        lines.append(f"| {severity} | {kind} | {n} |")
    return lines


def _coverage_lines(coverage: Coverage, total: int) -> list[str]:
    """The Markdown table of code scheme coverage.

    Args:
        coverage: Coverage per code scheme.
        total: Number of items in all.

    Returns:
        The table's lines.
    """
    lines = ["| Scheme | Regions named | Share | Distinct codes |", "|---|---:|---:|---:|"]
    for key, label in SCHEME_LABELS.items():
        item = coverage[key]
        lines.append(f"| {label} | {item['regions']} of {total} | {item['share']:.0%} | {item['distinct']} |")
    return lines


def _grade_lines(rows: Iterable[ProviderGrade]) -> list[str]:
    """The Markdown table of grades per vendor.

    Args:
        rows: Vendor and grade of each region.

    Returns:
        The table's lines.
    """
    counts = grades_by_provider(rows)
    used: list[Grade] = [g for g in GRADES if any(c[g] for c in counts.values())]
    lines = ["| Provider | Regions | " + " | ".join(used) + " |", "|---|---:|" + "---:|" * len(used)]
    for provider, count in counts.items():
        lines.append(
            f"| {provider} | {sum(count.values())} | " + " | ".join(str(count[g]) for g in used) + " |"
        )
    return lines


def _high_lines(calls: Iterable[CallRow]) -> list[str]:
    """The Markdown table of high-severity calls.

    Args:
        calls: Review calls.

    Returns:
        The table's lines.
    """
    lines = ["| Provider | Region | Kind | Detail |", "|---|---|---|---|"]
    for c in sorted(
        (c for c in calls if c["severity"] == "high"), key=lambda c: (c["provider"], c["region_id"])
    ):
        lines.append(f"| {c['provider']} | {c['region_id']} | {c['kind']} | {c['detail']} |")
    return lines
